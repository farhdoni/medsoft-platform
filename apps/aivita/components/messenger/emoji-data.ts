/** Emoji whose keywords match the query, in category order. */
export function searchEmoji(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const out: string[] = [];
  for (const cat of EMOJI_CATEGORIES) {
    for (const e of cat.emoji) {
      const words = EMOJI_KEYWORDS[e];
      if (words && words.some((w) => w.includes(q))) out.push(e);
    }
  }
  return out;
}
