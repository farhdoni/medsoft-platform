type ContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translations;
};

const I18nContext = createContext<ContextValue>({
  locale: 'ru',
  setLocale: () => {},
  t: translations.ru,
});

const STORAGE_KEY = 'admin-locale';

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('ru');

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
    if (saved && ['ru', 'en', 'uz'].includes(saved)) {
      setLocaleState(saved);
    }
  }, []);

  // Keep <html lang> honest — screen readers and the browser's own
  // translation prompt both read it, and the root layout can only ship a
  // static value.
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  function setLocale(l: Locale) {
    setLocaleState(l);
    localStorage.setItem(STORAGE_KEY, l);
  }

  return (
    <I18nContext.Provider value={{ locale, setLocale, t: translations[locale] }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

// Intl has no usable data for Uzbek in Chrome — `uz-UZ` renders as "M09 7,
// Mon" — so that one locale is spelled out by hand while ru/en go through
// Intl as normal.
const UZ_WEEKDAYS = ['yakshanba', 'dushanba', 'seshanba', 'chorshanba', 'payshanba', 'juma', 'shanba'];
const UZ_MONTHS = ['yanvar', 'fevral', 'mart', 'aprel', 'may', 'iyun', 'iyul', 'avgust', 'sentabr', 'oktabr', 'noyabr', 'dekabr'];

/**
 * "5 лет" / "5 years" / "5 yil". Russian picks one of three forms by the last
 * digit, with the 11-14 exception; English needs two; Uzbek needs one.
 */
export function formatYears(total: number, locale: Locale): string {
  if (locale === 'uz') return `${total} yil`;
  if (locale === 'en') return `${total} ${total === 1 ? 'year' : 'years'}`;
  const mod10 = total % 10;
  const mod100 = total % 100;
  if (mod100 >= 11 && mod100 <= 14) return `${total} лет`;
  if (mod10 === 1) return `${total} год`;
  if (mod10 >= 2 && mod10 <= 4) return `${total} года`;
  return `${total} лет`;
}

/** "понедельник, 7 сентября" / "dushanba, 7 sentabr" / "Monday, 7 September" */
export function formatLongDate(date: Date, locale: Locale): string {
  if (locale === 'uz') {
    return `${UZ_WEEKDAYS[date.getDay()]}, ${date.getDate()} ${UZ_MONTHS[date.getMonth()]}`;
  }
  return date.toLocaleDateString(locale === 'ru' ? 'ru-RU' : 'en-GB', {
    weekday: 'long',
    day: 'numeric',
    month: 'long',
  });
}
