import { resetRun } from './fixtures';

const APP_URL = 'http://localhost:3005';

// Страницы, которые шаги A…V трогают раньше всего — прогреть их здесь, а не
// ждать, пока это сделает первый тест.
const WARMUP_PATHS = ['/ru/sign-in', '/ru/home', '/ru/messenger', '/ru/ai-chat'];

/**
 * Ждёт, пока дев-сервер поднимется, и дёргает ключевые страницы, чтобы Next
 * скомпилировал их ДО начала прогона.
 *
 * Next dev компилирует страницу лениво, при первом запросе — это может занять
 * несколько секунд на каждый route. Раньше эта компиляция случайно попадала
 * внутрь первого теста и съедала часть его таймаута сама по себе: тест валился
 * не из-за поведения приложения, а из-за холодного старта сервера. Явный
 * прогон здесь выносит эту стоимость из тестового времени в setup-время, где
 * она не считается провалом.
 */
async function warmupApp() {
  const deadline = Date.now() + 90_000;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(`${APP_URL}${WARMUP_PATHS[0]}`);
      if (res.ok) break;
    } catch { /* сервер ещё не слушает порт */ }
    await new Promise((r) => setTimeout(r, 1000));
  }

  for (const path of WARMUP_PATHS) {
    try {
      await fetch(`${APP_URL}${path}`);
    } catch {
      // Не блокирующая: если конкретный маршрут недоступен (например,
      // редиректит без сессии в петлю), первый реальный тест всё равно его
      // скомпилирует — прогрев экономит время, а не является условием запуска.
    }
  }
}

/**
 * Один раз на прогон: чистит скриншоты и накопленный отчёт, затем прогревает
 * дев-сервер.
 *
 * Именно globalSetup, а не начало spec-файла: Playwright перезапускает воркер
 * после каждого упавшего теста, и очистка из модуля спеки стирала бы всё,
 * что собрано до падения.
 */
export default async function globalSetup() {
  resetRun();
  await warmupApp();
}
