-- 0056: удаление чата — cleared_at на conversation_participants.
--
-- Одна колонка на оба сценария удаления. Почему одной достаточно и второй
-- признак («удалён из диалога») не нужен:
--
--   «удалить у меня»     — cleared_at ставится на МОЙ participant-ряд.
--   «удалить у обоих»    — тот же cleared_at ставится на ОБА ряда, плюс
--                          массовый soft-delete messages.deleted_at.
--
-- Различие между сценариями лежит не в participant-ряду, а в том, тронуты ли
-- сообщения: при «у меня» они целы и у собеседника, при «у обоих» помечены
-- удалёнными для всех. Отдельный флаг хранил бы ровно ту же информацию, что
-- уже выводится из messages.deleted_at, и создал бы второй источник правды.
--
-- cleared_at работает как ЛИЧНАЯ отсечка истории, а не только как «скрыть из
-- списка» — лента диалога отдаёт мне лишь сообщения новее моего cleared_at.
-- Это и делает «чат стёрся у меня» правдой в самом диалоге, а не только в
-- списке, и не требует пер-пользовательских копий сообщений.
--
-- Новое сообщение возвращает диалог в список, но не отменяет удаление:
-- cleared_at остаётся на месте, а список сравнивает её с last_message_at
-- диалога — диалог видно, только если после отсечки что-то написали, и видно
-- ровно это. Снимать cleared_at было бы неверно: вместе с диалогом вернулась
-- бы и стёртая переписка. Отличие от архива сохраняется с другой стороны:
-- archived_at не сбрасывается никогда, потому что полка — осознанный выбор.
--
-- Строка conversations НЕ удаляется никогда и этой миграцией не затрагивается:
-- на неё каскадом висят support_tickets.conversation_id (тикет с перепиской)
-- и consultation_invoices.conversation_id (счета за консультации) — оба
-- ON DELETE CASCADE, то есть физическое удаление диалога снесло бы и тикет
-- поддержки, и финансовые записи.
--
-- timestamptz(3) и nullable — как pinned_at/muted_until/archived_at из 0036:
-- NULL это «не удалён», миллисекундная точность round-trip'ится через JSON.

ALTER TABLE "conversation_participants" ADD COLUMN IF NOT EXISTS "cleared_at" timestamptz(3);
